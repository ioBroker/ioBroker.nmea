/**
 * A word in the language of the system, English if there is none
 *
 * @param lang the language of the system
 * @param key the word
 */
export function getWord(lang: string, key: WordKey): string {
    return (WORDS[lang] || EN)[key] || EN[key];
}

/** Port and starboard as a pilot head shows them after a wind angle: `130°P` (en), `130°B` (de) */
const WIND_SIDE: Record<string, { port: string; starboard: string }> = {
    en: { port: 'P', starboard: 'S' },
    de: { port: 'B', starboard: 'S' },
    ru: { port: 'Л', starboard: 'П' },
    uk: { port: 'Л', starboard: 'П' },
    pl: { port: 'L', starboard: 'P' },
    nl: { port: 'B', starboard: 'S' },
    fr: { port: 'B', starboard: 'T' },
    it: { port: 'B', starboard: 'T' },
    pt: { port: 'B', starboard: 'E' },
    es: { port: 'B', starboard: 'E' },
    'zh-cn': { port: '左', starboard: '右' },
};

/**
 * The letter of the side for a wind angle, as the native autopilot widget shows it
 *
 * @param lang the language of the system
 */
export function getWindSide(lang: string): { port: string; starboard: string } {
    return WIND_SIDE[lang] || WIND_SIDE.en;
}
