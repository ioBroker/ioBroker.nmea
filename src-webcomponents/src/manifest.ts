/** The manifest of a component, as the build writes it */
export function getManifest(name: ComponentName): WebComponentManifest {
    const parts = PARTS[name];
    return {
        $schema: SCHEMA,
        manifestVersion: 1,
        tag: getTag(name),
        name: NAMES[name],
        description: parts.description,
        icon: parts.icon,
        module: getModuleFile(name),
        size: parts.size,
        settings: parts.settings,
    };
}
